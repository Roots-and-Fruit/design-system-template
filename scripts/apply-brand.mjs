function stampHtml(brand) {
  const pages = readdirSync(root).filter((f) => f.endsWith(".html"));
  for (const file of pages) {
    let html = read(file);
    let changed = false;

    const stamp = (attr, value) => {
      const re = new RegExp(
        `(<[^>]*\\bdata-brand="${attr}"[^>]*>)([\\s\\S]*?)(<\\/[^>]+>)`,
        "g",
      );
      const out = html.replace(re, (_, open, _inner, close) => {
        changed = true;
        return `${open}${escapeHtml(value)}${close}`;
      });
      html = out;
    };

    stamp("name", brand.name);
    stamp("tagline", brand.tagline);
    stamp("font-display", brand.fonts.displayName);
    stamp("font-body", brand.fonts.bodyName);
    stamp("font-mono", brand.fonts.monoName);

    const mk = brand.mediaKit || {};
    if (mk.shortName) stamp("shortName", mk.shortName);
    if (mk.boilerplate) stamp("boilerplate", mk.boilerplate);
    if (mk.oneLiner) stamp("oneLiner", mk.oneLiner);
    if (mk.website) {
      stamp("website", mk.website);
      const webHref = html.replace(
        /(<[^>]*\bdata-brand="website"[^>]*\bhref=")[^"]*(")/g,
        (_, a, b) => {
          changed = true;
          return `${a}${mk.website}${b}`;
        },
      );
      html = webHref;
    }
    if (mk.contactEmail) {
      stamp("contactEmail", mk.contactEmail);
      const mailHref = html.replace(
        /(<[^>]*\bdata-brand="contactEmail"[^>]*\bhref=")[^"]*(")/g,
        (_, a, b) => {
          changed = true;
          return `${a}mailto:${mk.contactEmail}${b}`;
        },
      );
      html = mailHref;
    }

    html = html.replace(
      /<title([^>]*)\bdata-brand-title="([^"]+)"([^>]*)>[\s\S]*?<\/title>/g,
      (_, a, page, b) => {
        changed = true;
        return `<title${a}data-brand-title="${page}"${b}>${escapeHtml(page)} — ${escapeHtml(brand.name)} Design System</title>`;
      },
    );

    if (changed) write(file, html);
  }
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function syncEmbed() {
  const result = spawnSync(process.execPath, [join(root, "sync-design-md-embed.mjs")], {
    cwd: root,
    encoding: "utf8",
  });
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
  if (result.status !== 0) {
    throw new Error("sync-design-md-embed.mjs failed");
  }
}

function reportLeftovers(brand) {
  if (brand.name === "Example Brand") {
    console.log('\nPlaceholder check: brand.json still has name "Example Brand".');
    console.log("Set placeholder:false and rename when the fork is real.\n");
    return;
  }
  const scanFiles = [
    "DESIGN.md",
    "README.md",
    "AGENTS.md",
    ...readdirSync(root).filter((f) => f.endsWith(".html")),
  ];
  const hits = [];
  for (const file of scanFiles) {
    if (read(file).includes("Example Brand")) hits.push(file);
  }
  if (hits.length) {
    console.log('\nLeftover "Example Brand" still in:');
    for (const h of hits) console.log(`  - ${h}`);
    console.log("Rewrite DESIGN.md prose where needed.\n");
  } else {
    console.log('\nNo leftover "Example Brand" strings in scanned files.\n');
  }
  if (brand.placeholder) {
    console.log('brand.json still has "placeholder": true — set to false when customised.\n');
  }
}

const brand = loadBrand();
console.log(`Applying brand: ${brand.name}`);
applyTokens(brand);
applyFonts(brand);
applyDesignMd(brand);
stampHtml(brand);
syncEmbed();
reportLeftovers(brand);
console.log("Done. Open customize.html for the remaining checklist (prose, assets).");
