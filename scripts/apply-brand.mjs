#!/usr/bin/env node
/**
 * Apply brand.json across the kit.
 *
 * Agents: edit ../brand.json, then run `npm run customize` from the repo root
 * (or `node scripts/apply-brand.mjs`). This is the only mechanical sync step.
 *
 * Writes:
 *   - css/tokens.css   (region between @@brand markers)
 *   - css/fonts.css    (@import URL)
 *   - DESIGN.md        (front-matter name, description, colors, type stacks, radii)
 *   - *.html           ([data-brand] stamps + <title data-brand-title>)
 *   - design-md.html   (via sync-design-md-embed.mjs)
 *
 * Does NOT rewrite DESIGN.md prose below the front matter (except the three
 * typography family names in backticks). Agents must still describe the brand.
 *
 * Viewing the reference site never requires this script.
 */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

function read(rel) {
  return readFileSync(join(root, rel), "utf8");
}

function write(rel, text) {
  writeFileSync(join(root, rel), text, "utf8");
  console.log(`  wrote ${rel}`);
}

function loadBrand() {
  const brand = JSON.parse(read("brand.json"));
  const required = ["name", "tagline", "description", "colors", "fonts", "rounded"];
  for (const key of required) {
    if (brand[key] == null) throw new Error(`brand.json missing "${key}"`);
  }
  for (const key of [
    "primary",
    "accent",
    "paper",
    "ink",
    "ink-deep",
    "surface",
    "on-primary",
    "on-accent",
  ]) {
    if (!brand.colors[key]) throw new Error(`brand.json colors missing "${key}"`);
  }
  return brand;
}

function applyTokens(brand) {
  const c = brand.colors;
  const f = brand.fonts;
  const r = brand.rounded;
  const k = brand.knobs || {};
  const block = `  /* @@brand:start — generated by scripts/apply-brand.mjs from brand.json. Do not edit by hand. */
  --cds-paper: ${c.paper};
  --cds-paper-deep: ${c["paper-deep"]};
  --cds-surface: ${c.surface};
  --cds-panel: ${c.panel};
  --cds-panel-deep: ${c["panel-deep"]};
  --cds-panel-soft: ${c["panel-soft"]};

  --cds-ink: ${c.ink};
  --cds-ink-deep: ${c["ink-deep"]};
  --cds-ink-muted: ${c["ink-muted"]};
  --cds-ink-soft: ${c["ink-soft"]};
  --cds-rule: ${c.rule};

  --cds-primary: ${c.primary};
  --cds-primary-deep: ${c["primary-deep"]};
  --cds-primary-soft: ${c["primary-soft"]};
  --cds-on-primary: ${c["on-primary"]};

  --cds-accent: ${c.accent};
  --cds-accent-soft: ${c["accent-soft"]};
  --cds-on-accent: ${c["on-accent"]};

  --cds-primary-1: ${c["primary-1"]};
  --cds-primary-2: ${c["primary-2"]};
  --cds-primary-3: ${c["primary-3"]};
  --cds-primary-4: var(--cds-primary);
  --cds-primary-5: ${c["primary-5"]};

  --cds-success: ${c.success};
  --cds-success-bg: ${c["success-soft"]};
  --cds-warning: ${c.warning};
  --cds-warning-bg: ${c["warning-soft"]};
  --cds-danger: ${c.danger};
  --cds-danger-bg: ${c["danger-soft"]};
  --cds-info: var(--cds-primary);
  --cds-info-bg: var(--cds-primary-soft);

  --cds-chart-1: var(--cds-primary);
  --cds-chart-2: var(--cds-accent);
  --cds-chart-3: var(--cds-success);
  --cds-chart-4: var(--cds-ink-muted);

  --cds-surface-dark: ${c["surface-dark"]};
  --cds-on-dark: ${c["on-dark"]};
  --cds-on-dark-muted: ${c["on-dark-muted"]};

  --cds-font-display: ${f.displayStack};
  --cds-font-body: ${f.bodyStack};
  --cds-font-mono: ${f.monoStack};

  --cds-weight-regular: ${f.weightRegular};
  --cds-weight-semibold: ${f.weightSemibold};
  --cds-weight-bold: ${f.weightBold};

  --cds-radius-sm: ${r.sm};
  --cds-radius: ${r.md};
  --cds-radius-lg: ${r.lg};
  --cds-radius-pill: ${r.pill};

  --cds-button-radius: ${k.buttonRadius || "var(--cds-radius-pill)"};
  --cds-heading-font: ${k.headingFont || "var(--cds-font-display)"};
  /* @@brand:end */`;

  const css = read("css/tokens.css");
  const next = css.replace(
    /\/\* @@brand:start[\s\S]*?\/\* @@brand:end \*\//,
    block,
  );
  if (next === css) {
    throw new Error(
      "css/tokens.css is missing @@brand:start / @@brand:end markers.",
    );
  }
  write("css/tokens.css", next);
}

function applyFonts(brand) {
  const css = read("css/fonts.css");
  const url = brand.fonts.googleImport;
  const next = css.replace(
    /@import url\("[^"]+"\);/,
    `@import url("${url}");`,
  );
  if (next === css && !css.includes(url)) {
    throw new Error("css/fonts.css: could not find @import url(...) to replace");
  }
  write("css/fonts.css", next);
}

function yamlQuote(value) {
  const s = String(value);
  if (/^[A-Za-z0-9_./+-]+$/.test(s) && !s.includes(" ")) return s;
  return JSON.stringify(s);
}

